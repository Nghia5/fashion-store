
CREATE TABLE IF NOT EXISTS Users (
    Id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name         VARCHAR(100) NOT NULL,
    Email        VARCHAR(150) NOT NULL UNIQUE,
    PasswordHash VARCHAR(255) NOT NULL,
    Role         VARCHAR(20)  NOT NULL DEFAULT 'user',
    Phone        VARCHAR(20)  NULL,
    Avatar       VARCHAR(500) NULL,
    IsActive     BOOLEAN NOT NULL DEFAULT TRUE,
    CreatedAt    TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS Categories (
    Id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name        VARCHAR(100) NOT NULL,
    Slug        VARCHAR(150) NOT NULL UNIQUE,
    Gender      VARCHAR(20)  NULL,
    Description VARCHAR(500) NULL,
    Image       VARCHAR(500) NULL,
    SortOrder   INT NOT NULL DEFAULT 0,
    IsActive    BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS Products (
    Id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name         VARCHAR(200)  NOT NULL,
    Slug         VARCHAR(250)  NOT NULL UNIQUE,
    Description  TEXT          NULL,
    CategoryId   INT NULL REFERENCES Categories(Id),
    Gender       VARCHAR(20)   NULL,
    Brand        VARCHAR(100)  NULL,
    Price        NUMERIC(18,0) NOT NULL DEFAULT 0,
    SalePrice    NUMERIC(18,0) NULL,
    Images       TEXT          NULL,
    Tags         VARCHAR(500)  NULL,
    IsFeatured   BOOLEAN NOT NULL DEFAULT FALSE,
    IsNewArrival BOOLEAN NOT NULL DEFAULT FALSE,
    Rating       NUMERIC(3,2)  NOT NULL DEFAULT 0,
    NumReviews   INT NOT NULL DEFAULT 0,
    Sold         INT NOT NULL DEFAULT 0,
    IsActive     BOOLEAN NOT NULL DEFAULT TRUE,
    CreatedAt    TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS ProductVariants (
    Id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ProductId INT NOT NULL REFERENCES Products(Id) ON DELETE CASCADE,
    Color     VARCHAR(50) NULL,
    Size      VARCHAR(20) NULL,
    Stock     INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS Carts (
    Id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UserId    INT NOT NULL REFERENCES Users(Id) ON DELETE CASCADE,
    UpdatedAt TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT UQ_Cart_User UNIQUE (UserId)
);

CREATE TABLE IF NOT EXISTS CartItems (
    Id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CartId    INT NOT NULL REFERENCES Carts(Id) ON DELETE CASCADE,
    ProductId INT NULL REFERENCES Products(Id),
    Name      VARCHAR(200) NOT NULL,
    Image     VARCHAR(500) NULL,
    Price     NUMERIC(18,0) NOT NULL,
    Color     VARCHAR(50)  NULL,
    Size      VARCHAR(20)  NULL,
    Quantity  INT NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS Orders (
    Id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UserId        INT NULL REFERENCES Users(Id),
    OrderNumber   VARCHAR(20)  NOT NULL UNIQUE,
    FullName      VARCHAR(100) NOT NULL,
    Phone         VARCHAR(20)  NOT NULL,
    Street        VARCHAR(200) NOT NULL,
    District      VARCHAR(100) NULL,
    City          VARCHAR(100) NOT NULL,
    PaymentMethod VARCHAR(50)  NOT NULL DEFAULT 'cod',
    OrderStatus   VARCHAR(30)  NOT NULL DEFAULT 'pending',
    TotalPrice    NUMERIC(18,0) NOT NULL DEFAULT 0,
    ShippingFee   NUMERIC(18,0) NOT NULL DEFAULT 0,
    Note          VARCHAR(500) NULL,
    CreatedAt     TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS OrderItems (
    Id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OrderId   INT NOT NULL REFERENCES Orders(Id) ON DELETE CASCADE,
    ProductId INT NULL REFERENCES Products(Id),
    Name      VARCHAR(200) NOT NULL,
    Image     VARCHAR(500) NULL,
    Price     NUMERIC(18,0) NOT NULL,
    Quantity  INT NOT NULL DEFAULT 1,
    Color     VARCHAR(50)  NULL,
    Size      VARCHAR(20)  NULL
);

CREATE TABLE IF NOT EXISTS Reviews (
    Id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ProductId INT NOT NULL REFERENCES Products(Id) ON DELETE CASCADE,
    UserId    INT NOT NULL REFERENCES Users(Id),
    Rating    INT NOT NULL CHECK (Rating BETWEEN 1 AND 5),
    Comment   VARCHAR(1000) NULL,
    CreatedAt TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS Wishlist (
    UserId    INT NOT NULL REFERENCES Users(Id) ON DELETE CASCADE,
    ProductId INT NOT NULL REFERENCES Products(Id),
    PRIMARY KEY (UserId, ProductId)
);

CREATE TABLE IF NOT EXISTS UserAddresses (
    Id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UserId    INT NOT NULL REFERENCES Users(Id) ON DELETE CASCADE,
    FullName  VARCHAR(100) NOT NULL,
    Phone     VARCHAR(20)  NOT NULL,
    Street    VARCHAR(200) NOT NULL,
    District  VARCHAR(100) NULL,
    City      VARCHAR(100) NOT NULL,
    IsDefault BOOLEAN NOT NULL DEFAULT FALSE
);
